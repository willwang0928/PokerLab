"""Render calibration results as Markdown (``docs/calibration/report.md``)."""

from __future__ import annotations

from typing import Any

from .policies import POLICY_BY_NAME


def _p(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def _p1(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def _bb(m: float | None, se: float | None) -> str:
    if m is None:
        return "–"
    return f"{m:+.2f} ± {1.96 * (se or 0):.2f}"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def render(data: dict[str, Any]) -> str:
    L: list[str] = ["# PokerLab calibration report (generated)", ""]
    c = data["config"]
    L += [
        "Generated by `python -m pokerlab.calibration` "
        f"(seed {c['seed']}, {c['hands']} hands per policy in sessions of "
        f"{c['session_hands']}, {c['rollouts']} paired rollouts per oracle evaluation, "
        f"{c['boot']} bootstrap replicates). Methodology and interpretation: "
        "`docs/calibration.md`. Every number here is an estimate from simulation.",
        "",
    ]
    L += _synthetic(data["synthetic"])
    if "discovery" in data:
        L += [
            "## Discovery run: the v0.4.4 coach",
            "",
            "The same simulated players and seeds, graded by the coach as it was in v0.4.4. "
            "These oracle results are the evidence for the v0.4.5 coaching changes "
            "(raises facing a bet are no longer the recommended answer). The sections after "
            "this one use the v0.4.5 coach.",
            "",
        ]
        L += _oracle(data["discovery"]["oracle"], level="###")
        rows = []
        for dname, by_n in data["discovery"]["confusion"].items():
            for n, cm in by_n.items():
                m = cm["injected"]
                rows.append([dname, n, _p(m["precision"]), _p(m["recall"]), _p1(m["fpr"])])
        L += ["### Detection against injected tendencies, v0.4.4 coach grades", ""]
        L += _table(["detector", "N", "precision", "recall", "FPR"], rows)
    if "policies" in data:
        L += _policies(data["policies"])
        L += _oracle(data["oracle"])
        L += _detection(data)
    return "\n".join(L)


def _synthetic(syn: dict[str, Any]) -> list[str]:
    names = list(syn)
    reps = syn[names[0]]["reps"]
    L = [
        "## 1. Detector statistics on synthetic data",
        "",
        f"Known flag rates, {reps} replicates per cell; identical streams for both detectors. "
        "The threshold is a 15% flagged rate: rates at or below it should rarely be "
        "reported (false positives); rates above it should be (power).",
        "",
    ]
    L += ["### P(reported as a leak), one weakness, by true rate and opportunities", ""]
    # Keys come back as strings (and text-sorted) when results are reloaded from JSON.
    ns = sorted(next(iter(syn[names[0]]["leak_by_rate"].values())), key=float)
    rows = []
    for rate in syn[names[0]]["leak_by_rate"]:
        for name in names:
            rows.append([rate, name] + [_p(syn[name]["leak_by_rate"][rate][n]) for n in ns])
    L += _table(["true rate", "detector"] + [f"n={n}" for n in ns], rows)
    rows = []
    for name in names:
        s = syn[name]
        rows.append(
            [
                name,
                _p(s["familywise"]["0.15"]["40"]),
                _p(s["familywise"]["0.15"]["160"]),
                _p(s["familywise"]["0.10"]["160"]),
                _p(s["sequential"]["0.10"]),
                _p(s["sequential"]["0.15"]),
                _p(s["dependence"]["icc=0.0"]),
                _p(s["dependence"]["icc=0.6"]),
                _p(s["spurious_concentration"]["40"]),
                _p(s["spurious_concentration"]["160"]),
                _p(s["true_concentration"]["150"]),
                _p(s["spurious_trend"]["40"]),
                _p(s["spurious_trend"]["160"]),
            ]
        )
    L += ["### Error rates", ""]
    L += _table(
        [
            "detector",
            "any false leak, 6 at 15%, n=40",
            "same, n=160",
            "6 at 10%, n=160",
            "ever flagged over 300 looks, 10%",
            "same, 15%",
            "15%, 3 per hand, ICC 0",
            "ICC 0.6",
            "spurious concentration n=40",
            "n=160",
            "true river concentration found",
            "spurious trend n=40",
            "n=160",
        ],
        rows,
    )
    rows = []
    sn = sorted(next(iter(syn[names[0]]["strength_by_rate"].values())), key=float)
    for rate in syn[names[0]]["strength_by_rate"]:
        for name in names:
            v = syn[name]["strength_by_rate"][rate]
            rows.append([rate, name] + [_p(v[n]) for n in sn])
    L += ["### P(reported as a strength) by true flagged rate (threshold 12%)", ""]
    L += _table(["true rate", "detector"] + [f"n={n}" for n in sn], rows)
    return L


def _policies(pol: dict[str, Any]) -> list[str]:
    L = ["## 2. Simulated players", ""]
    rows = []
    for name, p in pol.items():
        spec = POLICY_BY_NAME[name]
        rows.append(
            [
                f"`{name}`",
                spec.description,
                ", ".join(spec.targets) or "none",
                str(p["hands"]),
                str(p["graded"]),
                str(p["deviations"]),
                _p(p["flagged"] / p["graded"] if p["graded"] else None),
                f"{p['net_bb_per_100']:+.0f}",
            ]
        )
    L += _table(
        [
            "policy",
            "injected behaviour",
            "expected detector finding",
            "hands",
            "graded decisions",
            "deviations fired",
            "flagged",
            "bb/100 (noisy)",
        ],
        rows,
    )
    share = {k: v["share_with_several"] for k, v in pol["baseline"]["multi"].items()}
    L += [
        "Hands holding more than one opportunity of the same weakness (baseline): "
        + ", ".join(f"{k} {_p(v)}" for k, v in share.items())
        + ".",
        "",
    ]
    return L


def _oracle(o: dict[str, Any], level: str = "##") -> list[str]:
    L = [
        f"{level} 3. Independent oracle: what decisions actually cost",
        "",
        "Mean of (final stack after the chosen action − after the alternative) in big "
        "blinds per decision, from paired multi-street rollouts with the true cards and "
        "policies, ± 95% interval. Negative = the chosen action lost chips. *costly*/"
        "*gains* need the interval to exclude 0 and at least 15 evaluations.",
        "",
    ]
    L += ["### Injected deviations versus the baseline action", ""]
    rows = [
        [k.replace("|", " / "), str(v["n"]), _bb(v["mean_bb"], v["se_bb"]), v["verdict"]]
        for k, v in sorted(o["deviation"].items())
    ]
    L += _table(["policy / deviation", "n", "Δ bb", "verdict"], rows)
    L += [
        "### Coach flags: chosen action versus the coach's preferred one",
        "",
        "If the coach's flags are right, the chosen action should lose chips against the "
        "alternative it recommended (Δ < 0). `coach Δ` is the coach's own one-street "
        "estimate for the same pairs.",
        "",
    ]
    rows = [
        [
            k,
            str(v["n"]),
            _bb(v["mean_bb"], v["se_bb"]),
            _p(v["share_negative"]),
            "–" if v["coach_mean_bb"] is None else f"{v['coach_mean_bb']:+.2f}",
            v["verdict"],
        ]
        for k, v in sorted(o["flag"].items())
    ]
    L += _table(["tag", "n", "oracle Δ bb", "share Δ<0", "coach Δ bb", "verdict"], rows)
    rows = [
        [k.replace("|", " / robust="), str(v["n"]), _bb(v["mean_bb"], v["se_bb"]), v["verdict"]]
        for k, v in sorted(o["flag_by_confidence"].items())
    ]
    L += ["### Coach flags by confidence", ""]
    L += _table(["confidence / robust", "n", "oracle Δ bb", "verdict"], rows)
    rows = [
        [k.replace("|", " / "), str(v["n"]), _bb(v["mean_bb"], v["se_bb"]), v["verdict"]]
        for k, v in sorted(o["flag_by_street"].items())
        if v["n"] >= 10
    ]
    L += ["### Coach flags by street and tag (n ≥ 10)", ""]
    L += _table(["street / tag", "n", "oracle Δ bb", "verdict"], rows)
    rows = [
        [k, str(v["n"]), _bb(v["mean_bb"], v["se_bb"]), v["verdict"]]
        for k, v in sorted(o["control"].items())
    ]
    L += [
        "### Decisions graded good: chosen versus the best other option",
        "",
        "Should not be clearly negative.",
        "",
    ]
    L += _table(["confidence", "n", "oracle Δ bb", "verdict"], rows)
    return L


def _detection(data: dict[str, Any]) -> list[str]:
    det, truth = data["detection"], data["truth"]
    L = [
        "## 4. Leak detection on simulated players",
        "",
        "P(weakness reported as a leak) in bootstrap samples of N hands (whole hands "
        "resampled from each policy's run). Bold = a weakness the injected tendency "
        "targets. Results at N=800 resample the whole pool and inherit its quirks.",
        "",
    ]
    keys = list(next(iter(truth.values())))
    keys = [k for k in keys if not k.startswith("_")]
    for dname in ("v0.4.5", "v0.4.4"):
        L += [f"### Detector {dname}", ""]
        rows = []
        for policy, by in det["bootstrap"].items():
            for size, cell in sorted(by.get(dname, {}).items(), key=lambda x: int(x[0])):
                if int(size) not in (100, 200, 400, 800):
                    continue
                vals = []
                for k in keys:
                    v = _p(cell["leak"][k])
                    vals.append(f"**{v}**" if truth[policy][k]["injected"] else v)
                rows.append([f"`{policy}`", str(size)] + vals)
        L += _table(["policy", "N"] + keys, rows)
    L += [
        "### Precision, recall and false-positive rate",
        "",
        "Expected counts over all (policy, weakness) pairs. *Injected*: positives are "
        "the weaknesses a policy's injected tendency targets; every other report counts as "
        "a false positive, even if the player really has that weakness. *Oracle-"
        "confirmed*: positives are (policy, weakness) pairs whose coach-flagged decisions "
        "the oracle finds costly; pairs where the oracle finds no clear cost count as "
        "negatives only if it finds them *gaining*, otherwise they are left out.",
        "",
    ]
    rows = []
    for dname, by_n in data["confusion"].items():
        for n, cm in by_n.items():
            for truth_kind, m in cm.items():
                rows.append(
                    [
                        dname,
                        n,
                        truth_kind,
                        _p(m["precision"]),
                        _p(m["recall"]),
                        _p1(m["fpr"]),
                        f"{m['tp']:.1f}",
                        f"{m['fp']:.1f}",
                        f"{m['fn']:.1f}",
                    ]
                )
    L += _table(
        ["detector", "N", "ground truth", "precision", "recall", "FPR", "TP", "FP", "FN"], rows
    )
    L += ["### Ground truth per policy (oracle verdict on coach-flagged decisions)", ""]
    rows = []
    for policy, row in truth.items():
        cells = []
        for k in keys:
            t = row[k]
            cells.append(("inj, " if t["injected"] else "") + f"{t['confirmed']} ({t['flags_n']})")
        rows.append([f"`{policy}`"] + cells)
    L += _table(["policy"] + keys, rows)
    L += ["### Concentration and trend checks (N=800 bootstrap; full sequence)", ""]
    for dname in ("v0.4.5", "v0.4.4"):
        for policy, by in det["bootstrap"].items():
            cell = by.get(dname, {}).get(800) or by.get(dname, {}).get("800")
            if not cell:
                continue
            tc = cell["target_condition_named"]
            if tc:
                L.append(
                    f"- {dname} `{policy}`: target condition named when the leak is "
                    f"found: " + ", ".join(f"{k} {_p(v)}" for k, v in tc.items())
                )
            if cell["leaks_with_other_condition"]:
                L.append(
                    f"- {dname} `{policy}`: leaks naming a condition that was not "
                    f"injected: {_p(cell['leaks_with_other_condition'])}"
                )
    for policy, s in det["sequence"].items():
        for dname in ("v0.4.5", "v0.4.4"):
            trends = s[dname]["trend"]
            if trends:
                L.append(
                    f"- {dname} `{policy}` full run: trends "
                    + ", ".join(f"{k}: {v}" for k, v in trends.items())
                )
        looks = s["ever_in_repeated_looks"]
        L.append(
            f"- `{policy}` ever reported when re-checked every 25 hands: v0.4.5 "
            f"{looks['v0.4.5'] or 'none'}; v0.4.4 {looks['v0.4.4'] or 'none'}"
        )
    L.append("")
    return L
